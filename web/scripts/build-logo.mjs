// Builds the AQUILO logo assets from the vector wordmark extracted from the client's 2023 catalogue
// (scraped/brand/aquilo-wordmark-catalogue.svg, via scripts/extract_logo.py).
// Outputs: src/data/logo-paths.ts (per-letter paths for animation) and public/brand/*.svg.
// Usage (from web/): node scripts/build-logo.mjs
import { readFile, writeFile, mkdir } from "node:fs/promises";

const SRC = new URL("../../scraped/brand/aquilo-wordmark-catalogue.svg", import.meta.url);
const svg = await readFile(SRC, "utf8");
const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join("");

// Catalogue coordinates: wordmark bbox and the ® text position (from the PDF text span).
const X0 = 811.64, Y0 = 271.839, S = 10;
const REG = { cx: (971.28 - X0) * S, cy: (271.19 - Y0) * S, r: 31 };

const fmt = (n) => (Math.round(n * 10) / 10).toString();
const norm = (path) =>
  path.replace(/(-?\d+\.?\d*) (-?\d+\.?\d*)/g, (_, x, y) => `${fmt((+x - X0) * S)} ${fmt((+y - Y0) * S)}`);

const subs = d.split(/(?=M)/).filter((s) => s.trim()).map(norm);
const bbox = (s) => {
  const n = s.match(/-?\d+\.?\d*/g).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1);
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
};

// Group counters (inner shapes) with the letter whose outline contains them.
const items = subs.map((s) => ({ s, b: bbox(s) })).sort((a, b) => (b.b.x1 - b.b.x0) - (a.b.x1 - a.b.x0));
const groups = [];
for (const it of items) {
  const g = groups.find((g) => it.b.x0 >= g.b.x0 - 1 && it.b.x1 <= g.b.x1 + 1);
  if (g) g.parts.push(it.s); else groups.push({ b: it.b, parts: [it.s] });
}
groups.sort((a, b) => a.b.x0 - b.b.x0);
if (groups.length !== 6) throw new Error(`expected 6 letters, got ${groups.length}`);

const W = Math.ceil(REG.cx + REG.r + 6), top = Math.floor(REG.cy - REG.r - 6), H = Math.ceil(Math.max(...groups.map((g) => g.b.y1)) + 4);
const letters = "AQUILO".split("").map((char, i) => ({ char, d: groups[i].parts.join("") }));

await writeFile(new URL("../src/data/logo-paths.ts", import.meta.url), `// Generated by scripts/build-logo.mjs from the vector wordmark in the client's catalogue. Do not edit.
export const LOGO_VIEWBOX = "0 ${top} ${W} ${H - top}";
/** Letter area only (no ®), for effects clipped to the letterforms. */
export const LOGO_BOUNDS = { width: ${Math.ceil(groups[5].b.x1)}, height: ${Math.ceil(Math.max(...groups.map((g) => g.b.y1)))} };
export const LOGO_REGISTERED = ${JSON.stringify({ cx: +fmt(REG.cx), cy: +fmt(REG.cy), r: REG.r })};
export const LOGO_LETTERS = ${JSON.stringify(letters, null, 1)} as const;
`);

const regSvg = (fill) =>
  `<g fill="none" stroke="${fill}" stroke-width="4.5"><circle cx="${fmt(REG.cx)}" cy="${fmt(REG.cy)}" r="${REG.r - 2}"/></g>` +
  `<text x="${fmt(REG.cx)}" y="${fmt(REG.cy + 14)}" text-anchor="middle" font-family="Arial, Helvetica, sans-serif" font-weight="700" font-size="40" fill="${fill}">R</text>`;
await mkdir(new URL("../public/brand/", import.meta.url), { recursive: true });
for (const [name, fill] of [["aquilo-logo-black", "#000000"], ["aquilo-logo-white", "#ffffff"], ["aquilo-logo-champagne", "#c8a97e"]]) {
  const body = letters.map((l) => `<path d="${l.d}"/>`).join("\n");
  await writeFile(new URL(`../public/brand/${name}.svg`, import.meta.url),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 ${top} ${W} ${H - top}" width="${W / 4}" height="${(H - top) / 4}">\n<title>AQUILO</title>\n<g fill="${fill}" fill-rule="evenodd">\n${body}\n</g>\n${regSvg(fill)}\n</svg>\n`);
}
console.log("letters", letters.map((l, i) => `${l.char}:${groups[i].parts.length}`).join(" "), "viewBox", `0 ${top} ${W} ${H - top}`);
